// Generates an obs-shaderfilter HLSL snippet that warps a keyboard quad in the source
// to fill the output. The matrix H_inv maps OUTPUT uv (0..1) -> SOURCE uv (0..1).
// We pass the 9 entries of H_inv as separate float uniforms; the shader reconstructs
// the matrix and does a per-pixel projective transform.

export function buildShader(Hinv) {
  const m = [...Hinv]; // length 9, row-major

  const fmt = (n) => {
    if (!isFinite(n)) return '0.0';
    return n.toFixed(8);
  };

  // Default values bake the current calibration directly into the shader so it works
  // without any sliders being touched. The annotations make values editable too.
  const decl = (name, val, lo, hi) => `uniform float ${name}<
    string label = "${name.replace(/_/g, ' ')}";
    string widget_type = "slider";
    float minimum = ${lo};
    float maximum = ${hi};
    float step = 0.0000001;
> = ${fmt(val)};`;

  // Each entry has a generous range so the slider can still be used for nudging.
  const lines = [];
  const names = ['H00','H01','H02','H10','H11','H12','H20','H21','H22'];
  for (let i = 0; i < 9; i++) {
    lines.push(decl(names[i], m[i], -10, 10));
  }

  return `// Generated by Keyboard Calibrator
// Inverse homography: output_uv -> source_uv
// Drop this into an obs-shaderfilter Shader filter on your overhead camera source.

${lines.join('\n')}

float4 mainImage(VertData v_in) : TARGET {
    // v_in.uv is the output uv in [0,1] with origin at the top-left.
    float2 o = v_in.uv;

    // Apply H_inv as a 3x3 projective transform.
    float w = H20 * o.x + H21 * o.y + H22;
    float2 s = float2(
        (H00 * o.x + H01 * o.y + H02) / w,
        (H10 * o.x + H11 * o.y + H12) / w
    );

    // Outside the source frame -> transparent.
    if (s.x < 0.0 || s.x > 1.0 || s.y < 0.0 || s.y > 1.0) {
        return float4(0.0, 0.0, 0.0, 0.0);
    }

    return image.Sample(textureSampler, s);
}
`;
}

export function buildExportJSON({ Hfwd, Hinv, srcW, srcH, outW, outH, srcQuad, dstQuad }) {
  return {
    schema: 'piano-calibrator/v1',
    source: { width: srcW, height: srcH },
    output: { width: outW, height: outH },
    src_quad_pixels: srcQuad,          // [[x,y]*4] TL,TR,BR,BL in source pixels
    dst_quad_pixels: dstQuad,          // [[x,y]*4] TL,TR,BR,BL in output pixels
    homography_forward_uv: Array.from(Hfwd),  // 3x3 row-major, source_uv -> output_uv
    homography_inverse_uv: Array.from(Hinv),  // 3x3 row-major, output_uv -> source_uv
    note: 'Both matrices operate in normalized UV space (0..1) with top-left origin.',
  };
}
